//go:build ignore

// Generates ../data.go from Unicode's emoji-test.txt:
//
//	curl -sSfLO https://unicode.org/Public/emoji/latest/emoji-test.txt
//	go run ./internal/emoji/gen/main.go emoji-test.txt
package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strconv"
	"strings"
)

// maxVersion skips emoji newer than fonts and phones commonly show.
const maxVersion = 15.1

var line = regexp.MustCompile(`^([0-9A-F ]+?)\s*; fully-qualified\s*# \S+ E(\d+\.\d+) (.+)$`)

func main() {
	f, err := os.Open(os.Args[1])
	if err != nil {
		panic(err)
	}
	defer f.Close()
	var b strings.Builder
	b.WriteString("// Code generated by gen/main.go from Unicode's emoji-test.txt; DO NOT EDIT.\n\npackage emoji\n\nvar all = []Emoji{\n")
	group, n := "", 0
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		t := sc.Text()
		if g, ok := strings.CutPrefix(t, "# group: "); ok {
			group = g
			continue
		}
		mt := line.FindStringSubmatch(t)
		if mt == nil || group == "Component" {
			continue
		}
		if v, _ := strconv.ParseFloat(mt[2], 64); v > maxVersion {
			continue
		}
		var r []rune
		skin := false
		for _, cp := range strings.Fields(mt[1]) {
			c, _ := strconv.ParseUint(cp, 16, 32)
			if c >= 0x1F3FB && c <= 0x1F3FF {
				skin = true
			}
			r = append(r, rune(c))
		}
		if skin {
			continue // one of each, without skin tones
		}
		fmt.Fprintf(&b, "\t{%q, %q, %q},\n", string(r), mt[3], group)
		n++
	}
	b.WriteString("}\n")
	if err := os.WriteFile("internal/emoji/data.go", []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
	fmt.Println(n, "emoji")
}
